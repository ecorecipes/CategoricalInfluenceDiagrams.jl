# Exceptions of CategoricalInfluenceDiagrams (ADR 0013, ADR 0015). Every exception the
# package defines lives in this file, with its `showerror` method, and the module includes
# this file before any other.
#
# - The package defines more than one exception type, so they share the abstract type
#   `OpenInfluenceDiagramError`, which subtypes BayesianNetworks' `BayesNetError` (the
#   nearest root this package depends on).
# - Carry the offending variable and decision names in the fields and the message. Library
#   code never calls a bare `error("...")`.
# - Invalid arguments and keywords raise `ArgumentError`, not a type from this file.
# - A typed error from a lower package passes through unchanged, and the docstring of the
#   function that raises it says so: BayesianNetworks' `InterfaceError`,
#   `InterfaceMismatchError`, `NameClashError`, `DuplicateGeneratorError`,
#   `CyclicBayesNetError`, `DanglingReferenceError` and `MissingAttributeError`, and
#   InfluenceDiagrams' `DecisionUniquenessError`, `InvalidInformationSetError` and
#   `DecisionPrecedenceCycleError`; and, from the semantics, BayesianNetworks'
#   `MissingKernelError`, `KernelBindingError` and `ModelTooLargeError`, InfluenceDiagrams'
#   `IncompleteStrategyError`, `PolicySignatureError`, `MissingUtilityError` and
#   `UtilityScopeError`, and FiniteKernels' `SpaceMismatchError`.
# - A docstring names another package's type as a code span, never with `@ref`.

"""
    OpenInfluenceDiagramError

Abstract supertype of every exception introduced by CategoricalInfluenceDiagrams.jl. It is
a subtype of BayesianNetworks' `BayesNetError`, so `e isa AnyBayesNetError` catches these
errors too.
"""
abstract type OpenInfluenceDiagramError <: BayesNetError end

"""
    ObservabilityMismatchError(variable, position, left, right, context)

Two interface variables that are glued together agree in name, states and reference but
not in observability: one side declares `variable` `:observed` (remembered information a
later decision may read) and the other `:hidden` (ADR 0018, decision 2). `position` is the
index in the interface (or in the `along` list, or the junction) where the difference was
found, `left` and `right` are the two flags, and `context` says which operation compared
them.
"""
struct ObservabilityMismatchError <: OpenInfluenceDiagramError
    variable::Symbol
    position::Int
    left::Symbol
    right::Symbol
    context::String
end

function Base.showerror(io::IO, e::ObservabilityMismatchError)
    return print(io, "ObservabilityMismatchError: ", e.context, ": variable :", e.variable,
                 " at position ", e.position, " is :", e.left, " on the left but :",
                 e.right, " on the right; glued interface variables must agree on ",
                 "observability")
end

"""
    DiagramInterfaceError(rule, variable, by, kind)

A violation of the typed-interface rule of open influence diagrams (ADR 0018, decision 2)
that `BayesianNetworks` and `InfluenceDiagrams` have no type for:

- rule 2, an input-foot variable has a generator in the apex: input `variable` is
  generated by the mechanism (`kind = :mechanism`) or the decision (`kind = :decision`)
  named `by`;
- rule 3, a decision reads a hidden input: decision `by` has `variable`, an input-foot
  variable declared `:hidden`, in its information set (`kind = :hidden_input`).

The other rules are reported by the lower packages' types: rule 1 by `DuplicateGeneratorError`
and `DecisionUniquenessError`, rule 4 (a utility scope reads an apex variable) by
`DanglingReferenceError`, rule 5 by `CyclicBayesNetError`, `InvalidInformationSetError` and
`DecisionPrecedenceCycleError`, and rule 6 by [`NoForgettingError`](@ref).
"""
struct DiagramInterfaceError <: OpenInfluenceDiagramError
    rule::Int
    variable::Symbol
    by::Symbol
    kind::Symbol
end

function Base.showerror(io::IO, e::DiagramInterfaceError)
    print(io, "DiagramInterfaceError: rule ", e.rule, " ")
    if e.kind === :hidden_input
        return print(io, "(a decision reads only internal or observed input-foot ",
                     "variables) is violated: decision :", e.by,
                     " has the hidden input :", e.variable,
                     " in its information set; declare it observed or remove the arc")
    end
    return print(io, "(an input-foot variable has no generator in the apex) is violated: ",
                 "input :", e.variable, " is generated by the ", e.kind, " :", e.by)
end

"""
    NoForgettingError(decision, variable, earlier)

Rule 6 of the typed-interface rule (ADR 0018, decision 2): the components of a composite
had no-forgetting, but the composite does not. Decision `earlier` precedes `decision` in
the composite, and `variable` (in the information set of `earlier`, or its action) is not
in the information set of `decision`: the arc `variable -> decision` is missing. Across a
boundary this means that `variable` was not passed on as an `:observed` interface variable,
or that the later component's decision does not read it.
"""
struct NoForgettingError <: OpenInfluenceDiagramError
    decision::Symbol
    variable::Symbol
    earlier::Symbol
end

function Base.showerror(io::IO, e::NoForgettingError)
    return print(io, "NoForgettingError: the components have no-forgetting but the ",
                 "composite does not: decision :", e.decision, " comes after decision :",
                 e.earlier, " but does not know :", e.variable,
                 " (the information arc :", e.variable, " -> :", e.decision,
                 " is missing); pass :", e.variable,
                 " across the boundary as an observed variable and add it to the ",
                 "information set of :", e.decision,
                 ", or compose with `no_forgetting = false`")
end

"""
    DuplicatePolicyError(decision)

[`merge_strategies`](@ref) received two strategies that both have a policy for the
decision named `decision`. The strategy of a composite is the disjoint union of its
components' strategies (ADR 0018, decision 3), so each decision name may come from one
component only.
"""
struct DuplicatePolicyError <: OpenInfluenceDiagramError
    decision::Symbol
end

function Base.showerror(io::IO, e::DuplicatePolicyError)
    return print(io, "DuplicatePolicyError: decision :", e.decision,
                 " has a policy in more than one of the merged strategies; the strategy ",
                 "of a composite is the disjoint union of its components' strategies")
end
